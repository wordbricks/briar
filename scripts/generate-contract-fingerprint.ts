import { resolve } from "node:path";

const args = process.argv.slice(2);
const isCheck = args.includes("--check");
const imageFlag = args.indexOf("--image");
const repoRoot = resolve(import.meta.dir, "..");
const imagePath = resolve(
  repoRoot,
  imageFlag >= 0
    ? (args[imageFlag + 1] ?? "packages/contracts/briar.contracts.image.binpb")
    : "packages/contracts/briar.contracts.image.binpb",
);

const image = await Bun.file(imagePath).arrayBuffer();
const digest = new Uint8Array(await crypto.subtle.digest("SHA-256", image));
const rows = Array.from({ length: 4 }, (_, row) =>
  Array.from(digest.slice(row * 8, row * 8 + 8))
    .map((byte) => `0x${byte.toString(16).padStart(2, "0")}`)
    .join(", ")
);

const typescript = `// Generated by scripts/generate-contract-fingerprint.ts. Do not edit.

/** SHA-256 of the canonical compiled Briar descriptor image. */
export const CONTRACTS_DESCRIPTOR_FINGERPRINT = new Uint8Array([
${rows.map((row) => `  ${row},`).join("\n")}
]);
`;

const rust = `// Generated by scripts/generate-contract-fingerprint.ts. Do not edit.

/// SHA-256 of the canonical compiled Briar descriptor image.
pub const CONTRACTS_DESCRIPTOR_FINGERPRINT: [u8; 32] = [
${rows.map((row) => `    ${row},`).join("\n")}
];
`;

const outputs = [
  {
    path: resolve(repoRoot, "packages/contracts/src/descriptor-fingerprint.ts"),
    contents: typescript,
  },
  {
    path: resolve(
      repoRoot,
      "packages/contracts/rust/src/descriptor_fingerprint.rs",
    ),
    contents: rust,
  },
] as const;

if (isCheck) {
  for (const output of outputs) {
    if (await Bun.file(output.path).text() !== output.contents) {
      console.error(`Generated descriptor fingerprint is stale: ${output.path}`);
      process.exitCode = 1;
    }
  }
} else {
  await Promise.all(outputs.map((output) => Bun.write(output.path, output.contents)));
}
